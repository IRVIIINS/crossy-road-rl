"""Add one training round ("block") to the repo and to the app.

  python add_stage.py --bundle results_bundle_round1.zip --id round1 --label "PC round 1" --date 2026-11-23
  python add_stage.py --bundle results_bundle_round2.zip --id round2 --label "PC round 2" --date 2026-11-24 --continues round1

What it does
  1. unpacks the small files of the bundle (tables, every run's learning curve and logs) into training_rounds/<id>/
  2. copies the round's winning player to models/expo_<id>.pt
  3. exports that player for the app: expo-game/src/ai/stages/<id>.json
  4. adds/updates the block in expo-game/src/ai/stages/stages.json (what the app shows on its TRAINING BLOCKS screen)
  5. regenerates expo-game/src/ai/stages/index.ts (the app's list of block weights)

--continues <id>  this round resumed the runs of an earlier round (overnight.py run again on the same folder): games and
                  hours of that earlier round are not counted twice.
--starts-from <id>  every run of this round started from that block's player (overnight.py --init): its games are added
                  to the cumulative total of the winning line.
"""
import argparse, csv, io, json, os, re, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
STAGES = os.path.join(ROOT, "expo-game", "src", "ai", "stages")
MANIFEST = os.path.join(STAGES, "stages.json")
KEEP = re.compile(r"^(results\.md|results\.csv|cross_eval\.md|status\.txt|started_at\.txt|[^/]+/(iterations\.csv|log\.txt|done\.json|stopped\.json)"
                  r"|maker_vs_new_player/training_log\.csv)$")


def load_manifest():
    if os.path.exists(MANIFEST):
        return json.load(open(MANIFEST, encoding="utf-8"))
    return {"note": "generated by add_stage.py - one entry per training block", "stages": []}


def export_weights(pt_bytes, dst):
    import torch
    sd = torch.load(io.BytesIO(pt_bytes), map_location="cpu")
    keys = sorted({k.split(".")[1] for k in sd if k.endswith("weight")}, key=int)
    layers = [{"w": [[round(float(v), 5) for v in row] for row in sd[f"net.{k}.weight"]],
               "b": [round(float(v), 5) for v in sd[f"net.{k}.bias"]]} for k in keys]
    json.dump({"layers": layers}, open(dst, "w"), separators=(",", ":"))


def read_csv(z, name):
    return list(csv.DictReader(io.TextIOWrapper(z.open(name), encoding="utf-8")))


def run_summary(z, job):
    """last row of a run's learning curve + its done/stopped json"""
    rows = read_csv(z, f"{job}/iterations.csv") if f"{job}/iterations.csv" in z.namelist() else []
    meta = {}
    for n in (f"{job}/done.json", f"{job}/stopped.json"):
        if n in z.namelist(): meta = json.load(z.open(n))
    return rows, meta


def checkpoint_iteration(ck, rows, meta):
    m = re.match(r"iter_(\d+)\.pt", ck)
    if m: return int(m.group(1))
    if ck == "best.pt": return int(meta.get("best_iteration", 0)) or (int(rows[-1]["iteration"]) if rows else 0)
    return int(rows[-1]["iteration"]) if rows else 0   # final.pt


def write_index(manifest):
    lines = ["// GENERATED by add_stage.py - do not edit. One entry per training block (see stages.json).",
             "// eslint-disable-next-line @typescript-eslint/no-require-imports",
             "export const STAGE_WEIGHTS: Record<string, any> = {"]
    for st in manifest["stages"]:
        lines.append(f'  {json.dumps(st["id"])}: require({json.dumps(st["weights"] if st["weights"].startswith(".") else "./" + st["weights"])}),')
    lines.append("};")
    open(os.path.join(STAGES, "index.ts"), "w").write("\n".join(lines) + "\n")


def add_original(manifest):
    """block 0: the player that shipped before the long runs (models/expo_best.pt = src/ai/weights.json)."""
    if any(s["id"] == "original" for s in manifest["stages"]): return
    manifest["stages"].insert(0, dict(
        id="original", label="Original", where="pc", date="2026-11 (before the long runs)",
        summary="First trained player (Double DQN + look-ahead, 5 seeds x 10,000 games, best seed shipped).",
        games=10_000, hours=None, gamesAllRuns=50_000, updates=None, startsFrom=None, continues=None, config="main",
        runs=5, winner=dict(job="main (best seed)", checkpoint="best.pt", iteration=None),
        test=dict(random=22.87, maker=7.12), testNote="300 unseen seeds, same test as the long runs (cross_eval.md of round 2)",
        curve=[], configs={}, weights="../weights.json"))   # the shipped src/ai/weights.json


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--bundle", required=True)
    p.add_argument("--id", required=True)
    p.add_argument("--label", required=True)
    p.add_argument("--date", required=True)
    p.add_argument("--summary", default="")
    p.add_argument("--continues", default=None)
    p.add_argument("--starts-from", default=None)
    a = p.parse_args()
    os.makedirs(STAGES, exist_ok=True)
    manifest = load_manifest()
    add_original(manifest)
    prev = {s["id"]: s for s in manifest["stages"]}
    out = os.path.join(ROOT, "training_rounds", a.id)
    os.makedirs(out, exist_ok=True)

    with zipfile.ZipFile(a.bundle) as z:
        names = z.namelist()
        for n in names:
            if KEEP.match(n):
                dst = os.path.join(out, n); os.makedirs(os.path.dirname(dst), exist_ok=True)
                with z.open(n) as src, open(dst, "wb") as f: shutil.copyfileobj(src, f)
        res = read_csv(z, "results.csv")
        for r in res:
            for k in ("selection_score", "test_random", "test_maker"): r[k] = float(r[k])
        top = max(res, key=lambda r: r["selection_score"])
        winner_pt = z.read("expo_best_long.pt") if "expo_best_long.pt" in names else z.read(f"{top['job']}/selected.pt")
        # per-config means (same table as results.md)
        configs = {}
        for r in res:
            configs.setdefault(r["job"].rsplit("_s", 1)[0], []).append(r)
        configs = {k: dict(runs=len(v), random=round(sum(x["test_random"] for x in v) / len(v), 2),
                           maker=round(sum(x["test_maker"] for x in v) / len(v), 2)) for k, v in configs.items()}
        # games / hours / updates, for the winner and for all runs
        rows, meta = run_summary(z, top["job"])
        it = checkpoint_iteration(top["checkpoint"], rows, meta)
        upto = [r for r in rows if int(r["iteration"]) <= it] or rows
        last = upto[-1] if upto else {}
        job_games, job_hours = {}, {}
        for r in res:
            rr, _ = run_summary(z, r["job"])
            job_games[r["job"]] = int(rr[-1]["episodes"]) if rr else 0
            job_hours[r["job"]] = round(float(rr[-1]["seconds"]) / 3600, 2) if rr else 0
        cross = z.read("cross_eval.md").decode("utf-8") if "cross_eval.md" in names else ""
        step = max(1, len(upto) // 60)
        curve = [[int(r["episodes"]), float(r["eval_random"]), float(r["eval_maker"])] for r in upto[::step]]

    open(os.path.join(ROOT, "models", f"expo_{a.id}.pt"), "wb").write(winner_pt)
    export_weights(winner_pt, os.path.join(STAGES, f"{a.id}.json"))

    games, hours, updates = int(last.get("episodes", 0)), float(last.get("seconds", 0)) / 3600, int(last.get("steps", 0))
    # a continued round re-uses the earlier round's runs: count only what was added in this round
    base = prev.get(a.continues)
    old_g, old_h = (base.get("jobGames", {}), base.get("jobHours", {})) if base else ({}, {})
    all_games = sum(g - old_g.get(j, 0) for j, g in job_games.items())
    all_hours = sum(h - old_h.get(j, 0) for j, h in job_hours.items())
    start = prev.get(a.starts_from)
    entry = dict(
        id=a.id, label=a.label, where="pc", date=a.date, summary=a.summary or f"{len(res)} runs; best: {top['job']}",
        # games / hours / updates of the winning player's whole line (from scratch, incl. a --starts-from block)
        games=games + (start["games"] if start else 0), hours=round(hours + ((start["hours"] or 0) if start else 0), 2),
        updates=updates + ((start.get("updates") or 0) if start else 0),
        # what this block itself added, over all its runs
        gamesAllRuns=all_games, cpuHoursAllRuns=round(all_hours, 1), jobGames=job_games, jobHours=job_hours,
        startsFrom=a.starts_from, continues=a.continues, runs=len(res),
        winner=dict(job=top["job"], checkpoint=top["checkpoint"], iteration=it),
        test=dict(random=top["test_random"], maker=top["test_maker"]),
        testNote="300 unseen seeds (results.md)", configs=configs, crossEval=cross, curve=curve, weights=f"{a.id}.json")
    manifest["stages"] = [s for s in manifest["stages"] if s["id"] != a.id] + [entry]
    json.dump(manifest, open(MANIFEST, "w", encoding="utf-8"), indent=1)
    write_index(manifest)
    print(f"added block {a.id}: winner {top['job']} {top['checkpoint']} (iteration {it}, {games} games, {hours:.1f} h), "
          f"test random {top['test_random']} maker {top['test_maker']}; files in training_rounds/{a.id}/")


if __name__ == "__main__":
    main()
